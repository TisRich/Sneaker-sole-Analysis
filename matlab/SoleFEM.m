
clc;
clear;
close all;

%% STEP 1: Define STL Files and Parameters

files = {'Update_FlatS.STL', 'CurvedS.STL'};
names = {'Flat Sole', 'Curved Sole'};

% Loading faces
loadFaces = {2, 3};

% Geometry conversion
stlScale = 0.01;
axisCorrection = [0.1, 0.1, 0.1];

% Mesh configuration
Hmax = 0.003;               % 3 mm
meshOrder = 'linear';
showMesh = true;

% Material properties
E = 25e6;                   % Young's modulus (Pa)
nu = 0.48;                  % Poisson's ratio

% Applied loading
F = 1946;                   % Target total force (N)
loadDirection = [0; 0; -1];

% Heel-strike loading region
heelRadius = 0.02;          % 2 cm radius (4 cm diameter)
heelOffset = 0.06;          % 6 cm from rear
heelAtMinX = true;          % Change if heel is at maximum X

% Figure viewing settings
viewAzimuth = -155;
viewElevation = 25;

% Existing results folder
folderName = 'Results_Figures';

% Model and result storage
Solemodel = cell(1,2);
meshes = cell(1,2);

midfootResults = cell(1,2);
heelResults = cell(1,2);

% Track only figures generated by this script
figHandles = gobjects(0);
figNames = {};

% Four simulation cases:
% Flat midfoot, flat heel, curved midfoot, curved heel
resultRows = table();

%% STEP 2: Import and Mesh Both Soles

for i = 1:numel(files)

    fprintf('\n====================================\n');
    fprintf('PROCESSING %s\n', names{i});
    fprintf('====================================\n');

    model = createpde('structural','static-solid');

    importGeometry(model, files{i});

    fprintf('Number of geometric faces: %d\n', ...
        model.Geometry.NumFaces);

    % Display face identification
    h = figure;

    pdegplot(model, ...
        'FaceLabels','on', ...
        'FaceAlpha',0.5);

    axis equal;
    view(3);

    title([names{i}, ' - Face Identification']);

    figHandles(end+1) = h;
    figNames{end+1} = ...
        [strrep(names{i},' ','_'), ...
        '_Face_Identification'];

    %% Correct Geometry

    scale(model.Geometry, axisCorrection);
    scale(model.Geometry, stlScale);

    %% Generate Mesh

    msh = generateMesh(model, ...
        'Hmax',Hmax, ...
        'GeometricOrder',meshOrder);

    fprintf('Nodes: %d\n',size(msh.Nodes,2));
    fprintf('Elements: %d\n',size(msh.Elements,2));

    % Check mesh dimensions
    P = msh.Nodes';

    dimensions_cm = ...
        (max(P,[],1)-min(P,[],1))*100;

    fprintf('Corrected mesh dimensions (cm):\n');
    fprintf('X = %.3f\n',dimensions_cm(1));
    fprintf('Y = %.3f\n',dimensions_cm(2));
    fprintf('Z = %.3f\n',dimensions_cm(3));

    Solemodel{i} = model;
    meshes{i} = msh;

    %% Preliminary Mesh Plot

    if showMesh

        h = figure;

        pdeplot3D(msh);

        axis equal;
        view(3);

        title([names{i}, ' - Preliminary Mesh']);

        figHandles(end+1) = h;
        figNames{end+1} = ...
            [strrep(names{i},' ','_'), ...
            '_Preliminary_Mesh'];

    end

end

%% STEP 3: Run Both Loading Cases

for i = 1:numel(files)

    model = Solemodel{i};
    msh = meshes{i};

    P = msh.Nodes';

    fprintf('\n====================================\n');
    fprintf('FEA: %s\n', names{i});
    fprintf('====================================\n');

    %% 3A. Material Properties

    structuralProperties(model, ...
        'YoungsModulus',E, ...
        'PoissonsRatio',nu);

    %% 3B. Boundary Conditions

    % Preserve existing support configuration:
    % Fix all faces except the loading face
    fixedFaces = setdiff( ...
        1:model.Geometry.NumFaces,loadFaces{i});

    structuralBC(model, ...
        'Face',fixedFaces, ...
        'Constraint','fixed');

    %% 3C. Identify Upper Loading Surface

    TR = triangulation(msh.Elements',msh.Nodes');

    surfaceTriangles = freeBoundary(TR);

    loadNodes = [];

    for f = loadFaces{i}

        nodes = findNodes(msh, ...
            'region','Face',f);

        loadNodes = [loadNodes;nodes(:)];

    end

    loadNodes = unique(loadNodes);

    mask = all(ismember( ...
        surfaceTriangles,loadNodes),2);

    loadTri = surfaceTriangles(mask,:);

    if isempty(loadTri)
        error('No loading triangles found for %s.',names{i});
    end

    %% 3D. Calculate Midfoot Loading Area

    midfootArea = calculateTriangleArea(P,loadTri);

    if ~isfinite(midfootArea) || midfootArea <= 0
        error('Invalid midfoot area for %s.',names{i});
    end

    midfootTraction = F/midfootArea;

    fprintf('\nMIDFOOT LOADING\n');
    fprintf('Area: %.6f m^2\n',midfootArea);
    fprintf('Traction: %.2f Pa\n',midfootTraction);

    %% 3E. Plot Midfoot Loading Region
    % Flat sole ONLY

    if i == 1

        h = figure;

        drawLoadingRegion( ...
            P,surfaceTriangles,loadTri);

        axis equal;
        view(3);

        title('Flat Sole - Midfoot Loading Region');

        figHandles(end+1) = h;
        figNames{end+1} = ...
            'Flat_Sole_Midfoot_Loading_Region';

    end

    %% 3F. Apply Midfoot Load

    midfootLoad = structuralBoundaryLoad(model, ...
        'Face',loadFaces{i}, ...
        'SurfaceTraction', ...
        midfootTraction*loadDirection);

    %% 3G. Solve Midfoot FEA

    solveTimer = tic;

    midfootResults{i} = solve(model);

    midfootSolveTime = toc(solveTimer);

    midStress = ...
        max(midfootResults{i}.VonMisesStress)/1e6;

    midDisp = ...
        max(midfootResults{i}.Displacement.Magnitude)*1000;

    fprintf('Midfoot max stress: %.4f MPa\n',midStress);
    fprintf('Midfoot max displacement: %.4f mm\n',midDisp);
    fprintf('Solve time: %.2f seconds\n',midfootSolveTime);

    %% 3H. Midfoot Stress Plot

    h = figure;

    pdeplot3D(midfootResults{i}.Mesh, ...
        'ColorMapData', ...
        midfootResults{i}.VonMisesStress/1e6);

    axis equal;
    view(3);
    colorbar;

    title([names{i}, ...
        ' - Midfoot Von Mises Stress (MPa)']);

    figHandles(end+1) = h;
    figNames{end+1} = ...
        [strrep(names{i},' ','_'), ...
        '_Midfoot_Stress'];

    %% 3I. Midfoot Displacement Plot

    h = figure;

    pdeplot3D(midfootResults{i}.Mesh, ...
        'ColorMapData', ...
        midfootResults{i}.Displacement.Magnitude*1000);

    axis equal;
    view(3);
    colorbar;

    title([names{i}, ...
        ' - Midfoot Displacement (mm)']);

    figHandles(end+1) = h;
    figNames{end+1} = ...
        [strrep(names{i},' ','_'), ...
        '_Midfoot_Displacement'];

    %% 3J. Store Midfoot Results

    row = table( ...
        string(names{i}), ...
        "Midfoot", ...
        F, ...
        midfootArea, ...
        midfootTraction, ...
        midStress, ...
        midDisp, ...
        midfootSolveTime, ...
        'VariableNames',{ ...
        'Sole','LoadingCase','TargetForce_N', ...
        'EstimatedArea_m2','Traction_Pa', ...
        'MaxStress_MPa','MaxDisplacement_mm', ...
        'SolveTime_s'});

    resultRows = [resultRows;row];

    %% STEP 4: Prepare Heel-Strike Loading Case

    % Remove the midfoot load before applying the heel load.
    % Retain material, fixtures, geometry, and mesh.
    delete(midfootLoad);

    %% 4A. Locate Heel Center

    xMin = min(P(loadNodes,1));
    xMax = max(P(loadNodes,1));

    if heelAtMinX

        heelX = xMin + heelOffset;

    else

        heelX = xMax - heelOffset;

    end

    heelY = ...
        (min(P(loadNodes,2)) + ...
         max(P(loadNodes,2)))/2;

    fprintf('\nHEEL-STRIKE LOADING\n');
    fprintf('Heel center X: %.4f m\n',heelX);
    fprintf('Heel center Y: %.4f m\n',heelY);

    %% 4B. Identify Circular Heel Patch

    % Centroids of eligible upper-surface triangles
    centroids = ( ...
        P(loadTri(:,1),:) + ...
        P(loadTri(:,2),:) + ...
        P(loadTri(:,3),:))/3;

    % Circular region projected onto XY plane
    distanceSquared = ...
        (centroids(:,1)-heelX).^2 + ...
        (centroids(:,2)-heelY).^2;

    patchMask = ...
        distanceSquared <= heelRadius^2;

    heelTri = loadTri(patchMask,:);

    if isempty(heelTri)
        error(['No heel patch triangles found for %s. ', ...
            'Check heel position and sole orientation.'], ...
            names{i});
    end

    %% 4C. Calculate Heel Loading Area

    heelArea = calculateTriangleArea(P,heelTri);

    if ~isfinite(heelArea) || heelArea <= 0
        error('Invalid heel area for %s.',names{i});
    end

    heelTraction = F/heelArea;

    fprintf('Heel patch estimated area: %.6f m^2\n', ...
        heelArea);

    fprintf('Heel patch traction: %.2f Pa\n', ...
        heelTraction);

    %% 4D. Plot Heel Loading Region
    % Flat sole ONLY

    if i == 1

        h = figure;

        drawLoadingRegion( ...
            P,surfaceTriangles,heelTri);

        axis equal;
        view(3);

        title('Flat Sole - Heel Strike Loading Region');

        figHandles(end+1) = h;
        figNames{end+1} = ...
            'Flat_Sole_HeelStrike_Loading_Region';

    end

    %% 4E. Define Spatial Heel Traction

    % Traction acts only within the circular region.
    % Function returns a 3 x N matrix when vectorized.

    heelLoadFcn = @(location,state) ...
        loadDirection .* ( ...
        heelTraction * double( ...
        (location.x-heelX).^2 + ...
        (location.y-heelY).^2 <= heelRadius^2));

    %% 4F. Apply Heel-Strike Load

    structuralBoundaryLoad(model, ...
        'Face',loadFaces{i}, ...
        'SurfaceTraction',heelLoadFcn, ...
        'Vectorized','on');

    %% 4G. Solve Heel-Strike FEA

    solveTimer = tic;

    heelResults{i} = solve(model);

    heelSolveTime = toc(solveTimer);

    heelStress = ...
        max(heelResults{i}.VonMisesStress)/1e6;

    heelDisp = ...
        max(heelResults{i}.Displacement.Magnitude)*1000;

    fprintf('Heel max stress: %.4f MPa\n',heelStress);
    fprintf('Heel max displacement: %.4f mm\n',heelDisp);
    fprintf('Solve time: %.2f seconds\n',heelSolveTime);

    %% 4H. Heel-Strike Stress Plot

    h = figure;

    pdeplot3D(heelResults{i}.Mesh, ...
        'ColorMapData', ...
        heelResults{i}.VonMisesStress/1e6);

    axis equal;
    view(3);
    colorbar;

    title([names{i}, ...
        ' - Heel Strike Von Mises Stress (MPa)']);

    figHandles(end+1) = h;
    figNames{end+1} = ...
        [strrep(names{i},' ','_'), ...
        '_HeelStrike_Stress'];

    %% 4I. Heel-Strike Displacement Plot

    h = figure;

    pdeplot3D(heelResults{i}.Mesh, ...
        'ColorMapData', ...
        heelResults{i}.Displacement.Magnitude*1000);

    axis equal;
    view(3);
    colorbar;

    title([names{i}, ...
        ' - Heel Strike Displacement (mm)']);

    figHandles(end+1) = h;
    figNames{end+1} = ...
        [strrep(names{i},' ','_'), ...
        '_HeelStrike_Displacement'];

    %% 4J. Store Heel-Strike Results

    row = table( ...
        string(names{i}), ...
        "Heel Strike", ...
        F, ...
        heelArea, ...
        heelTraction, ...
        heelStress, ...
        heelDisp, ...
        heelSolveTime, ...
        'VariableNames',{ ...
        'Sole','LoadingCase','TargetForce_N', ...
        'EstimatedArea_m2','Traction_Pa', ...
        'MaxStress_MPa','MaxDisplacement_mm', ...
        'SolveTime_s'});

    resultRows = [resultRows;row];

end

%% STEP 5: Combined Summary Table

fprintf('\n====================================\n');
fprintf('COMBINED MIDFOOT AND HEEL RESULTS\n');
fprintf('====================================\n');

disp(resultRows);

writetable(resultRows, ...
    fullfile(folderName, ...
    'Combined_Midfoot_HeelStrike_Results.xlsx'));

%% STEP 6: Adjust Views After Solving

% Changes figure presentation only.
% No mesh generation or FEA recalculation.

for k = 1:numel(figHandles)

    h = figHandles(k);

    axList = findall(h,'Type','axes');

    for j = 1:numel(axList)

        ax = axList(j);

        axis(ax,'equal');

        view(ax,viewAzimuth,viewElevation);

        camup(ax,[0 0 1]);

    end

end

%% STEP 7: Save All Figures

for k = 1:numel(figHandles)

    h = figHandles(k);
    fileName = figNames{k};

    exportgraphics(h, ...
        fullfile(folderName,[fileName '.png']), ...
        'Resolution',300);

    savefig(h, ...
        fullfile(folderName,[fileName '.fig']));

end

fprintf('\n====================================\n');
fprintf('COMBINED STATIC FEA COMPLETE\n');
fprintf('====================================\n');

fprintf('Figures saved: %d\n',numel(figHandles));
fprintf('Output folder: %s\n',folderName);

%% LOCAL FUNCTION 1: Triangle Surface Area

function A = calculateTriangleArea(P,tri)

    v1 = P(tri(:,2),:) - P(tri(:,1),:);
    v2 = P(tri(:,3),:) - P(tri(:,1),:);

    A = sum(0.5 * vecnorm( ...
        cross(v1,v2,2),2,2));

end

%% LOCAL FUNCTION 2: Plot Loading Region
% Gray = full sole exterior
% Red = selected loading region
% Black = boundary of selected region

function drawLoadingRegion(P,surfaceTri,selectedTri)

    ax = gca;

    hold(ax,'on');

    % Display full external sole geometry
    trisurf(surfaceTri, ...
        P(:,1),P(:,2),P(:,3), ...
        'FaceColor',[0.78 0.82 0.85], ...
        'EdgeColor','none', ...
        'FaceAlpha',0.25, ...
        'Parent',ax);

    % Highlight selected loading region
    trisurf(selectedTri, ...
        P(:,1),P(:,2),P(:,3), ...
        'FaceColor',[0.95 0.20 0.12], ...
        'EdgeColor','none', ...
        'FaceAlpha',1, ...
        'Parent',ax);

    % Extract all triangle edges
    edges = [ ...
        selectedTri(:,[1 2]); ...
        selectedTri(:,[2 3]); ...
        selectedTri(:,[3 1])];

    % Identify edges shared by only one selected triangle
    edges = sort(edges,2);

    [uniqueEdges,~,edgeID] = ...
        unique(edges,'rows');

    edgeCount = accumarray(edgeID,1);

    perimeterEdges = ...
        uniqueEdges(edgeCount == 1,:);

    % Draw perimeter edges in black
    n = size(perimeterEdges,1);

    if n > 0

        x = reshape([ ...
            P(perimeterEdges(:,1),1), ...
            P(perimeterEdges(:,2),1), ...
            nan(n,1)]',[],1);

        y = reshape([ ...
            P(perimeterEdges(:,1),2), ...
            P(perimeterEdges(:,2),2), ...
            nan(n,1)]',[],1);

        z = reshape([ ...
            P(perimeterEdges(:,1),3), ...
            P(perimeterEdges(:,2),3), ...
            nan(n,1)]',[],1);

        plot3(ax,x,y,z,'k-', ...
            'LineWidth',2);

    end

    axis(ax,'equal');
    view(ax,3);

    hold(ax,'off');

end
